"""Produce the evidence bundle under artifacts/: browser recordings, screenshots, journey traces and an HTML report.
Usage: python tests/e2e/record_all.py   (needs Playwright + Chromium; providers are stubbed by tests/e2e/server.py)"""
import html
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / "artifacts"; REC = ART / "browser-recordings"; SHOT = ART / "screenshots"; REP = ART / "playwright-report"
for d in (REC, SHOT, REP):
    d.mkdir(parents=True, exist_ok=True)
env = dict(os.environ, E2E_RECORD_DIR=str(REC), E2E_SLOWMO="220")
t0 = time.time()
j = subprocess.run([sys.executable, str(ROOT / "tests/e2e/run_e2e.py"), str(SHOT)], env=env, capture_output=True, text=True, cwd=ROOT)
print(j.stdout[-3000:], j.stderr[-1500:])
d = subprocess.run([sys.executable, str(ROOT / "tests/e2e/judge_demo.py"), str(REC), str(SHOT)], capture_output=True, text=True, cwd=ROOT)
print(d.stdout, d.stderr[-1500:])
raw = REC / "_raw"
if raw.exists():
    for f in raw.glob("*.webm"):
        f.unlink()
    raw.rmdir()
rows = re.findall(r"^(PASS|FAIL) (.+?)\s*(?:  (\S.*))?$", j.stdout, re.M)
passed = sum(1 for r in rows if r[0] == "PASS")
files = sorted(p for p in ART.rglob("*") if p.is_file() and p.name != "index.html" and "playwright-report" not in p.parts)
(ART / "recordings-index.json").write_text(json.dumps({"generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "journeys_passed": passed, "journeys_total": len(rows), "duration_s": round(time.time() - t0, 1),
    "files": [{"path": str(p.relative_to(ART)), "bytes": p.stat().st_size} for p in files]}, indent=2))
li = "".join(f'<li class="{r[0].lower()}"><b>{r[0]}</b> {html.escape(r[1])}{(" <code>" + html.escape(r[2]) + "</code>") if r[2] else ""}</li>' for r in rows)
shots = "".join(f'<figure><img src="../screenshots/{p.name}" loading="lazy" alt="{p.stem}"><figcaption>{p.stem}</figcaption></figure>' for p in sorted(SHOT.glob("*.png")))
vids = "".join(f'<h3>{p.name}</h3><video controls preload="metadata" src="../browser-recordings/{p.name}"></video>' for p in sorted(REC.glob("*.webm")))
(REP / "index.html").write_text(f'''<!doctype html><meta charset="utf-8"><title>FreshCode v5.1 browser journey report</title>
<style>body{{font:16px/1.5 system-ui;background:#f3ebdd;color:#3a2a4f;max-width:1100px;margin:30px auto;padding:0 16px}}li{{margin:6px 0;list-style:none}}.pass b{{color:#245c43}}.fail b{{color:#9a2b3e}}figure{{margin:0;display:inline-block;width:32%;vertical-align:top}}img{{width:100%;border:1px solid #d3c4bb;border-radius:8px}}video{{width:100%;border-radius:10px}}</style>
<h1>FreshCode AI v5.1: browser journey report</h1><p>Generated by tests/e2e/record_all.py (Playwright + Chromium). {passed}/{len(rows)} journeys passed. Providers are stubbed on the test server; everything else is real. This is a generated summary, not the @playwright/test HTML reporter. Trace: <code>browser-recordings/full-user-journey-trace.zip</code> (open with <code>playwright show-trace</code>).</p>
<ul>{li}</ul><h2>Recordings</h2>{vids}<h2>Screenshots</h2>{shots}''')
print(f"report: {REP/'index.html'} · {passed}/{len(rows)} journeys")
sys.exit(0 if passed == len(rows) and (REC / "judge-demo.webm").exists() and (REC / "full-user-journey.webm").exists() else 1)
